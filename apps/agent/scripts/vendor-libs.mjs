// Writes agent/lib/vendor/<lib>.ts, each exporting a library's browser build as a string, so the
// libraries artifacts load (`<script src="lib:echarts">`) are bundled by `eve build` instead of
// read from node_modules at runtime, which a production image does not have. Runs on install.
// The output is generated (git-ignored); the pinned version lives in apps/agent/package.json.
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import path from 'node:path'

const require = createRequire(import.meta.url)
const LIBRARIES = { echarts: 'echarts/dist/echarts.min.js' }
const out = path.join(import.meta.dirname, '../agent/lib/vendor')

await mkdir(out, { recursive: true })
for (const [name, file] of Object.entries(LIBRARIES)) {
  const source = await readFile(require.resolve(file), 'utf8')
  const { version } = JSON.parse(await readFile(require.resolve(`${name}/package.json`), 'utf8'))
  await writeFile(
    path.join(out, `${name}.ts`),
    `// Generated by scripts/vendor-libs.mjs from ${name}@${version}. Do not edit.\n` +
      `export const version = ${JSON.stringify(version)}\n` +
      `export default ${JSON.stringify(source)}\n`,
  )
  console.log(`vendored ${name}@${version} (${Math.round(source.length / 1024)} KB)`)
}
